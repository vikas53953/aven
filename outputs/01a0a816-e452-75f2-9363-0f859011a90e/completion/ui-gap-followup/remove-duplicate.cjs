'use strict';
const fs = require('node:fs');
const path = require('node:path');
const candidate = path.resolve(__dirname, 'candidate', 'polished.js');
let text = fs.readFileSync(candidate, 'utf8');
const oldText = "document.addEventListener('keydown',e=>{if((e.ctrlKey||e.metaKey)&&!e.altKey&&!one('dialog[open]')){if(e.key.toLowerCase()==='k'){e.preventDefault();openCommands();}else if(e.key.toLowerCase()==='f'&&currentView==='conversation'){e.preventDefault();openConversationFind();}}},true);";
const newText = "document.addEventListener('keydown',e=>{if((e.ctrlKey||e.metaKey)&&e.key.toLowerCase()==='k'&&!e.altKey&&!one('dialog[open]')){e.preventDefault();openCommands();}},true);";
const count = text.split(oldText).length - 1;
if (count !== 1) throw new Error('duplicate listener count ' + count);
text = text.replace(oldText, newText);
fs.writeFileSync(candidate, text);
const proofPath = path.resolve(__dirname, 'replacement-proof.json');
const proof = JSON.parse(fs.readFileSync(proofPath, 'utf8'));
proof.replacements = proof.replacements.filter(item => item.new !== oldText);
proof.candidateSha256 = require('node:crypto').createHash('sha256').update(fs.readFileSync(candidate)).digest('hex');
proof.generatedAt = new Date().toISOString();
proof.scope = 'UX-065 unavailable shortcut advertising only; UX-069 evidence pane focus return; frozen v9.1 UI candidate copy';
fs.writeFileSync(proofPath, JSON.stringify(proof, null, 2));
console.log(JSON.stringify({ candidateSha256: proof.candidateSha256, replacements: proof.replacements.length }));
